#include "water/water.h"

const unsigned char water_palette[] = {
    0x01, 0x00, 0x10, 0x30,
    0x01, 0x13, 0x21, 0x2C,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00
};

void setup_water_irq(unsigned char waterline) {
    *(unsigned char*)0xC001 = waterline;
    *(unsigned char*)0xC000 = waterline;
    *(unsigned char*)0xE001 = 0;
}